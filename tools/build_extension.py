"""Package the shared form rules as local MV3 code; no runtime eval or remote scripts."""
import argparse
from pathlib import Path

from coopcoach.apply import _CHOICES_JS, _FIELD_SAFETY_JS, _FILL_JS


def source():
    return ("// Generated by python -m tools.build_extension; edit coopcoach/apply.py instead.\n"
            "globalThis.coopShared = (() => {\n" + _FIELD_SAFETY_JS
            + "\nreturn {visible, safeField, fill: " + _FILL_JS + ", choices: " + _CHOICES_JS + "};\n})();\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "extension" / "form_shared.js"
    if args.check:
        if not path.exists() or path.read_text() != source():
            raise SystemExit("Shared extension rules are stale: run python -m tools.build_extension")
    else:
        path.write_text(source())


if __name__ == "__main__":
    main()
